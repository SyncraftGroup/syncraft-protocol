#[cfg(test)]
mod tests {
    use super::*;

    fn version() -> VersionInfo {
        VersionInfo {
            name: "My Server".into(),
            id: "my-server".into(),
            vanilla_version: "1.21.1".into(),
            loader: Loader::Fabric {
                loader_version: "0.16.10".into(),
            },
        }
    }

    fn files(path: &str) -> BTreeMap<PathBuf, SyncFile> {
        let mut map = BTreeMap::new();
        map.insert(
            PathBuf::from(path),
            SyncFile {
                state: Some(FileState {
                    size: 3,
                    hash: blake3::hash(b"abc"),
                }),
                mode: SyncMode::Strict,
            },
        );
        map
    }

    #[test]
    fn content_hash_is_deterministic() {
        let version = version();
        let a = files("mods/a.jar");

        assert_eq!(
            Manifest::content_hash(MANIFEST_SCHEMA, &version, &a),
            Manifest::content_hash(MANIFEST_SCHEMA, &version, &a)
        );
    }

    #[test]
    fn content_hash_changes_with_content_version_and_schema() {
        let version = version();
        let a = files("mods/a.jar");
        let b = files("mods/b.jar");

        let base = Manifest::content_hash(MANIFEST_SCHEMA, &version, &a);
        assert_ne!(base, Manifest::content_hash(MANIFEST_SCHEMA, &version, &b));
        assert_ne!(
            base,
            Manifest::content_hash(MANIFEST_SCHEMA + 1, &version, &a)
        );

        let mut other = version.clone();
        other.loader = Loader::Forge {
            loader_version: "47.2.0".into(),
        };
        assert_ne!(base, Manifest::content_hash(MANIFEST_SCHEMA, &other, &a));
    }

    #[test]
    fn cache_key_includes_minecraft_and_loader_versions() {
        let version = version();
        assert_eq!(version.cache_key(), "my-server-1.21.1-fabric-0.16.10");

        let mut other = version.clone();
        other.loader = Loader::Fabric {
            loader_version: "0.17.0".into(),
        };
        assert_ne!(version.cache_key(), other.cache_key());
    }
}
