use std::{
    collections::BTreeMap,
    io,
    path::{Path, PathBuf},
};

use serde::{Deserialize, Serialize};
use tokio::{
    fs::{self, File},
    io::AsyncReadExt,
};

/// Current wire format version of [`Manifest`].
///
/// Bump this whenever the meaning of an existing field changes or a field is
/// removed. Clients reject manifests whose schema differs from their own.
pub const MANIFEST_SCHEMA: u32 = 3;

#[derive(Debug, Deserialize, Serialize, Clone)]
pub enum Loader {
    Vanilla,
    Fabric { loader_version: String },
    Forge { loader_version: String },
    NeoForge { loader_version: String },
}

impl Loader {
    /// Short, filesystem-safe description, e.g. `fabric-0.16.10`.
    pub fn tag(&self) -> String {
        match self {
            Self::Vanilla => "vanilla".to_string(),
            Self::Fabric { loader_version } => format!("fabric-{loader_version}"),
            Self::Forge { loader_version } => format!("forge-{loader_version}"),
            Self::NeoForge { loader_version } => format!("neoforge-{loader_version}"),
        }
    }
}

#[derive(Debug, Deserialize, Serialize, Clone)]
pub struct VersionInfo {
    /// Display name shown to players and in the update log.
    pub name: String,
    /// Stable identifier used for file names on the client. Generated by
    /// `syncraft init`; renaming `name` does not affect it.
    pub id: String,
    pub vanilla_version: String,
    pub loader: Loader,
}

impl VersionInfo {
    /// Deterministic key for client-side caches.
    ///
    /// Includes the Minecraft and loader versions so that changing either one
    /// invalidates the cached metadata instead of silently reusing it.
    pub fn cache_key(&self) -> String {
        let raw = format!("{}-{}-{}", self.id, self.vanilla_version, self.loader.tag());
        raw.chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_') {
                    c
                } else {
                    '_'
                }
            })
            .collect()
    }
}

#[derive(Debug, Deserialize, Serialize, PartialEq, Eq, Clone)]
pub struct FileState {
    pub size: u64,
    pub hash: blake3::Hash,
}

impl FileState {
    pub async fn from_path(path: &Path) -> io::Result<Self> {
        let metadata = fs::metadata(path).await?;

        Ok(Self {
            hash: Self::hash(path).await?,
            size: metadata.len(),
        })
    }

    pub async fn hash(path: &Path) -> io::Result<blake3::Hash> {
        let mut file = File::open(path).await?;
        let mut hasher = blake3::Hasher::new();
        let mut buf = [0u8; 8192];

        loop {
            let n = file.read(&mut buf).await?;
            if n == 0 {
                break;
            }
            hasher.update(&buf[..n]);
        }

        Ok(hasher.finalize())
    }

    /// Whether the file at `path` already matches this state.
    ///
    /// Size is checked first: a differing size rules out a match without
    /// reading the whole file, which keeps start-up syncs cheap.
    pub async fn matches(&self, path: &Path) -> io::Result<bool> {
        let metadata = fs::metadata(path).await?;
        if metadata.len() != self.size {
            return Ok(false);
        }
        Ok(self.hash == Self::hash(path).await?)
    }
}

#[derive(Debug, Deserialize, Serialize, Clone, Copy, PartialEq, Eq, Default)]
#[serde(rename_all = "snake_case")]
pub enum SyncMode {
    /// Only provide the file when the client does not have it.
    #[serde(rename = "ifmissing")]
    IfMissing,
    /// Update managed files, but leave unmanaged files in the directory alone.
    Minimal,
    /// Mirror managed files and remove unmanaged files inside mirrored dirs.
    #[default]
    Strict,
    /// The client must not have this file.
    Forbidden,
}

/// Domain separator for manifest signatures.
const SIGNING_DOMAIN: &[u8] = b"syncraft-manifest-v1\0";

/// Bytes covered by [`Manifest::signature`]. Only the content hash is signed:
/// it already commits to the version info and the file list, and a signature
/// must stay valid for snapshots served through `?version=`.
pub fn manifest_signing_payload(version_hash: &str) -> Vec<u8> {
    let mut payload = Vec::with_capacity(SIGNING_DOMAIN.len() + version_hash.len());
    payload.extend_from_slice(SIGNING_DOMAIN);
    payload.extend_from_slice(version_hash.as_bytes());
    payload
}

/// Optional detached signature of the manifest.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ManifestSignature {
    /// Only `ed25519` is supported today.
    pub algorithm: String,
    /// Hex-encoded public key (32 bytes).
    pub key: String,
    /// Hex-encoded signature (64 bytes).
    pub value: String,
}

impl SyncMode {
    /// Stable byte used when hashing a manifest.
    fn discriminant(self) -> u8 {
        match self {
            Self::IfMissing => 0,
            Self::Minimal => 1,
            Self::Strict => 2,
            Self::Forbidden => 3,
        }
    }
}

#[derive(Debug, Deserialize, Serialize, Clone)]
pub struct SyncFile {
    pub state: Option<FileState>,
    pub mode: SyncMode,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct Manifest {
    /// Wire format version, see [`MANIFEST_SCHEMA`].
    pub schema: u32,
    /// Content hash over `version` + `files`. Identifies this exact file set.
    pub version_hash: String,
    /// Git commit this snapshot was published from, used for changelogs.
    /// Empty when the workspace has no commit yet.
    pub commit: String,
    pub version: VersionInfo,
    /// Suggested parallel downloads on the client (server-side setting).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub download_concurrency: Option<u8>,
    /// Optional detached signature, see [`ManifestSignature`].
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub signature: Option<ManifestSignature>,
    /// Sorted map: iteration order (and therefore the content hash) is stable.
    pub files: BTreeMap<PathBuf, SyncFile>,
}

impl Manifest {
    /// Deterministic hash of the manifest content.
    ///
    /// Note that `version_hash` is **not** derived from a git commit: the same
    /// commit can produce different file sets (e.g. when files are ignored by
    /// the mod filter), so the manifest hashes itself instead.
    pub fn content_hash(
        schema: u32,
        version: &VersionInfo,
        files: &BTreeMap<PathBuf, SyncFile>,
    ) -> String {
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"syncraft-manifest\0");
        hasher.update(&schema.to_le_bytes());

        hasher.update(version.name.as_bytes());
        hasher.update(&[0]);
        hasher.update(version.id.as_bytes());
        hasher.update(&[0]);
        hasher.update(version.vanilla_version.as_bytes());
        hasher.update(&[0]);
        match &version.loader {
            Loader::Vanilla => {
                hasher.update(b"vanilla");
            }
            Loader::Fabric { loader_version } => {
                hasher.update(b"fabric\0");
                hasher.update(loader_version.as_bytes());
            }
            Loader::Forge { loader_version } => {
                hasher.update(b"forge\0");
                hasher.update(loader_version.as_bytes());
            }
            Loader::NeoForge { loader_version } => {
                hasher.update(b"neoforge\0");
                hasher.update(loader_version.as_bytes());
            }
        }

        for (path, file) in files {
            hasher.update(&[0xff]);
            hasher.update(path.as_os_str().as_encoded_bytes());
            hasher.update(&[file.mode.discriminant()]);
            match &file.state {
                Some(state) => {
                    hasher.update(&[1]);
                    hasher.update(&state.size.to_le_bytes());
                    hasher.update(state.hash.as_bytes());
                }
                None => {
                    hasher.update(&[0]);
                }
            }
        }

        hasher.finalize().to_hex().to_string()
    }
}

